const translations: Record<Language, TranslationValues> = {
  en,
  'zh-CN': zhCN,
  'pt-BR': ptBR,
}

const languageLocales: Record<Language, string> = {
  en: 'en-US',
  'zh-CN': 'zh-CN',
  'pt-BR': 'pt-BR',
}

function detectLanguage(): Language {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    if (stored === 'en' || stored === 'zh-CN' || stored === 'pt-BR') {
      return stored
    }
  } catch {
    // Storage can be disabled; browser language remains a safe fallback.
  }
  const browserLanguage = navigator.language.toLowerCase()
  if (browserLanguage.startsWith('zh')) return 'zh-CN'
  if (browserLanguage.startsWith('pt')) return 'pt-BR'
  return 'en'
}

function translate(
  language: Language,
  key: TranslationKey,
  variables?: Variables,
) {
  let value: string = translations[language][key]
  if (!variables) return value
  for (const [name, replacement] of Object.entries(variables)) {
    value = value.replaceAll(`{${name}}`, String(replacement))
  }
  return value
}

type I18nContextValue = {
  language: Language
  locale: string
  setLanguage: (language: Language) => void
  t: (key: TranslationKey, variables?: Variables) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)
const fallbackContext: I18nContextValue = {
  language: 'en',
  locale: 'en-US',
  setLanguage: () => undefined,
  t: (key, variables) => translate('en', key, variables),
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(detectLanguage)

  useEffect(() => {
    document.documentElement.lang = language
    try {
      window.localStorage.setItem(STORAGE_KEY, language)
    } catch {
      // The selected language still works for the current session.
    }
  }, [language])

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      locale: languageLocales[language],
      setLanguage,
      t: (key, variables) => translate(language, key, variables),
    }),
    [language],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

// eslint-disable-next-line react-refresh/only-export-components
export function useI18n() {
  const context = useContext(I18nContext)
  return context ?? fallbackContext
}

